def _rotl32(x: int, n: int) -> int:
    return ((x << n) | (x >> (32 - n))) & 0xFFFFFFFF


def _add_m31(a: int, b: int) -> int:
    c = a + b
    return (c & 0x7FFFFFFF) + (c >> 31)


class _ZUC:
    """ZUC-128 内部状态机。"""

    def __init__(self, key: bytes, iv: bytes):
        if len(key) != 16 or len(iv) != 16:
            raise ValueError("ZUC-128 requires 16-byte key and 16-byte IV")
        self._lfsr: List[int] = [0] * 16
        self._r1 = 0
        self._r2 = 0
        self._init(key, iv)

    def _init(self, key: bytes, iv: bytes):
        for i in range(16):
            self._lfsr[i] = (
                (key[i] << 23) | (_D[i] << 8) | iv[i]
            ) & 0x7FFFFFFF

        self._r1 = 0
        self._r2 = 0

        for _ in range(32):
            w = self._bit_reorg()
            z = self._f(w[0], w[1], w[2])
            v = self._lfsr_with_init(w[3], z)
            self._lfsr[0] = v

    def _bit_reorg(self):
        s = self._lfsr
        x0 = ((s[15] & 0x7FFF8000) << 1) | (s[14] & 0xFFFF)
        x1 = ((s[11] & 0xFFFF) << 16) | (s[9] >> 15)
        x2 = ((s[7] & 0xFFFF) << 16) | (s[5] >> 15)
        x3 = ((s[2] & 0xFFFF) << 16) | (s[0] >> 15)
        return x0, x1, x2, x3

    def _f(self, x0: int, x1: int, x2: int) -> int:
        w = ((x0 ^ self._r1) + self._r2) & 0xFFFFFFFF
        w1 = (self._r1 + x1) & 0xFFFFFFFF
        w2 = self._r2 ^ x2
        u = self._l1((w1 << 16) | (w2 >> 16))
        v = self._l2((w2 << 16) | (w1 >> 16))
        self._r1 = self._s_box(u)
        self._r2 = self._s_box(v)
        return w

    @staticmethod
    def _l1(x: int) -> int:
        return x ^ _rotl32(x, 2) ^ _rotl32(x, 10) ^ _rotl32(x, 18) ^ _rotl32(x, 24)

    @staticmethod
    def _l2(x: int) -> int:
        return x ^ _rotl32(x, 8) ^ _rotl32(x, 14) ^ _rotl32(x, 22) ^ _rotl32(x, 30)

    @staticmethod
    def _s_box(x: int) -> int:
        b = [(x >> (24 - 8 * i)) & 0xFF for i in range(4)]
        s = [_SBOX0[b[0]], _SBOX1[b[1]], _SBOX0[b[2]], _SBOX1[b[3]]]
        return (s[0] << 24) | (s[1] << 16) | (s[2] << 8) | s[3]

    def _lfsr_with_init(self, x0: int, w: int) -> int:
        s = self._lfsr
        v = (
            _add_m31(_add_m31(_add_m31(_add_m31(_add_m31(
                _rotl32(s[15], 15) & 0x7FFFFFFF,
                _rotl32(s[13], 17) & 0x7FFFFFFF),
                _rotl32(s[10], 21) & 0x7FFFFFFF),
                _rotl32(s[4], 20) & 0x7FFFFFFF),
                _rotl32(s[0], 8) & 0x7FFFFFFF),
                s[0])
        ) & 0x7FFFFFFF
        v = _add_m31(v, (w ^ x0) & 0x7FFFFFFF)
        for i in range(15):
            self._lfsr[i] = self._lfsr[i + 1]
        return v

    def _lfsr_with_work(self) -> None:
        s = self._lfsr
        v = (
            _add_m31(_add_m31(_add_m31(_add_m31(_add_m31(
                _rotl32(s[15], 15) & 0x7FFFFFFF,
                _rotl32(s[13], 17) & 0x7FFFFFFF),
                _rotl32(s[10], 21) & 0x7FFFFFFF),
                _rotl32(s[4], 20) & 0x7FFFFFFF),
                _rotl32(s[0], 8) & 0x7FFFFFFF),
                s[0])
        ) & 0x7FFFFFFF
        for i in range(15):
            self._lfsr[i] = self._lfsr[i + 1]
        self._lfsr[15] = v

    def generate(self) -> int:
        """生成一个 32 位密钥字。"""
        x = self._bit_reorg()
        z = self._f(x[0], x[1], x[2]) ^ x[3]
        self._lfsr_with_work()
        return z & 0xFFFFFFFF

    def keystream(self, length: int) -> bytes:
        """生成 length 字节的密钥流。"""
        words = (length + 3) // 4
        ks = b""
        for _ in range(words):
            w = self.generate()
            ks += struct.pack(">I", w)
        return ks[:length]


def zuc_encrypt(key: bytes, iv: bytes, plaintext: bytes) -> bytes:
    """ZUC-128 流加密（加解密操作相同）。

    Args:
        key:       16 字节密钥
        iv:        16 字节初始向量
        plaintext: 明文字节

    Returns:
        密文字节
    """
    if len(key) != 16:
        raise ValueError("ZUC key must be 16 bytes")
    if len(iv) != 16:
        raise ValueError("ZUC IV must be 16 bytes")
    zuc = _ZUC(key, iv)
    ks = zuc.keystream(len(plaintext))
    return bytes(a ^ b for a, b in zip(plaintext, ks))


def zuc_decrypt(key: bytes, iv: bytes, ciphertext: bytes) -> bytes:
    """ZUC-128 流解密（与加密相同）。"""
    return zuc_encrypt(key, iv, ciphertext)
